/**
 * Parses raw lead text typically generated by web forms, e.g.:
 * "Message : Program: Not sure — advise me Preferred month: November 2026 Length of stay: Doctor to advise | Other-information: Form variant: r10-panchakarma | Campaign name: Panchakarma_India"
 */
export function parseRawEnquiryMessage(raw: string): {
  program?: string
  preferredMonth?: string
  lengthOfStay?: string
  formVariant?: string
  campaignName?: string
  customMessage?: string
} {
  if (!raw) return {}
  const res: {
    program?: string
    preferredMonth?: string
    lengthOfStay?: string
    formVariant?: string
    campaignName?: string
    customMessage?: string
  } = {}

  // Extract Program
  const progMatch = raw.match(/Program:\s*([^|\n\r]+?)(?=(Preferred month:|Length of stay:|Other-information:|Campaign name:|$))/i)
  if (progMatch?.[1]) res.program = progMatch[1].trim()

  // Extract Preferred month
  const monthMatch = raw.match(/Preferred month:\s*([^|\n\r]+?)(?=(Length of stay:|Other-information:|Campaign name:|Program:|$))/i)
  if (monthMatch?.[1]) res.preferredMonth = monthMatch[1].trim()

  // Extract Length of stay
  const stayMatch = raw.match(/Length of stay:\s*([^|\n\r]+?)(?=(Other-information:|Campaign name:|Program:|Preferred month:|$))/i)
  if (stayMatch?.[1]) res.lengthOfStay = stayMatch[1].trim()

  // Extract Form variant
  const variantMatch = raw.match(/Form variant:\s*([^|\n\r]+?)(?=(Campaign name:|Program:|Preferred month:|Length of stay:|$))/i)
  if (variantMatch?.[1]) res.formVariant = variantMatch[1].trim()

  // Extract Campaign name
  const campMatch = raw.match(/Campaign name:\s*([^|\n\r]+?)(?=(Form variant:|Program:|Preferred month:|Length of stay:|$))/i)
  if (campMatch?.[1]) res.campaignName = campMatch[1].trim()

  // Extract any direct custom customer message before "Program:" or after
  const clean = raw
    .replace(/Message\s*:\s*/i, '')
    .replace(/Program:\s*[^|\n\r]+/i, '')
    .replace(/Preferred month:\s*[^|\n\r]+/i, '')
    .replace(/Length of stay:\s*[^|\n\r]+/i, '')
    .replace(/Other-information:\s*/i, '')
    .replace(/Form variant:\s*[^|\n\r]+/i, '')
    .replace(/Campaign name:\s*[^|\n\r]+/i, '')
    .replace(/\|+/g, ' ')
    .trim()

  if (clean && clean.length > 2 && !clean.match(/^[—\-\s]+$/)) {
    res.customMessage = clean
  }

  return res
}

/**
 * Extracts UTM and tracking params from sourceUrl
 */
export function parseSourceUrlParams(urlStr?: string): {
  utmSource?: string
  utmMedium?: string
  utmCampaign?: string
  gclid?: string
  cleanUrl?: string
} {
  if (!urlStr) return {}
  try {
    const url = new URL(urlStr)
    return {
      utmSource: url.searchParams.get('utm_source') || undefined,
      utmMedium: url.searchParams.get('utm_medium') || undefined,
      utmCampaign: url.searchParams.get('utm_campaign') || undefined,
      gclid: url.searchParams.get('gclid') || undefined,
      cleanUrl: `${url.origin}${url.pathname}`,
    }
  } catch {
    return { cleanUrl: urlStr }
  }
}

/**
 * Normalizes phone numbers for WhatsApp link (digits only with country code)
 */
function toWhatsAppNumber(phone: string): string {
  const digits = phone.replace(/\D/g, '')
  if (digits.length === 10) return `91${digits}`
  return digits
}

